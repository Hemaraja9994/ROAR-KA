const BANKS: Record<Lang, Item[]> = {
  en: ENGLISH,
  kn: KANNADA,
  hi: HINDI,
};

export function getBank(lang: Lang): Item[] {
  return BANKS[lang];
}

export function getPractice(lang: Lang): Item[] {
  return BANKS[lang].filter((i) => i.practice);
}

export function getTestBank(lang: Lang): Item[] {
  return BANKS[lang].filter((i) => !i.practice);
}

export function findItem(lang: Lang, id: string): Item | undefined {
  return BANKS[lang].find((i) => i.id === id);
}
